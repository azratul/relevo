const dict: Record<Lang, Record<string, string>> = { en, es };

export let lang: Lang = (() => { try { return localStorage.getItem("relevo.lang") === "es" ? "es" : "en"; } catch { return "en"; } })();
export function setLang(l: Lang) { lang = l; try { localStorage.setItem("relevo.lang", l); } catch { /* private mode */ } document.documentElement.lang = l; }
export function has(k: string) { return k in en; }
export function t(k: string, v: Record<string, string | number> = {}): string {
  return (dict[lang][k] ?? en[k] ?? k).replace(/\{(\w+)\}/g, (_, x) => String(v[x] ?? ""));
}
export function msg(m: Msg | null | undefined): string {
  if (!m) return "";
  return "raw" in m ? m.raw : t(m.k, m.v);
}
